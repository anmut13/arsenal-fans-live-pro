/**
 * Cleanly generate a 3-letter code from any team name
 */
export function generateTeamCode(teamName: string): string {
  if (!teamName) return 'FC1';
  const existing = WORLD_TEAMS.find(
    (t) =>
      t.name.toLowerCase() === teamName.toLowerCase() ||
      t.shortName.toLowerCase() === teamName.toLowerCase()
  );
  if (existing) return existing.code;

  const clean = teamName.replace(/[^a-zA-Z\s]/g, '').trim();
  const words = clean.split(/\s+/).filter(Boolean);

  if (words.length >= 3) {
    return (words[0][0] + words[1][0] + words[2][0]).toUpperCase();
  }
  if (words.length === 2) {
    if (words[0].toUpperCase() === 'FC' || words[0].toUpperCase() === 'SC') {
      return words[1].slice(0, 3).toUpperCase();
    }
    if (words[1].toUpperCase() === 'FC' || words[1].toUpperCase() === 'SC') {
      return words[0].slice(0, 3).toUpperCase();
    }
    return words[0].slice(0, 3).toUpperCase();
  }
  return clean.slice(0, 3).toUpperCase();
}

/**
 * Instantly creates a complete custom Team object for any typed name
 */
export function createCustomTeam(name: string, customColor?: string): Team {
  const code = generateTeamCode(name);
  const id = name.toLowerCase().replace(/[^a-z0-9]/g, '');
  const colors = [
    { p: '#db0007', s: '#ffffff' },
    { p: '#034694', s: '#ffffff' },
    { p: '#008057', s: '#ffffff' },
    { p: '#DA291C', s: '#FFE500' },
    { p: '#6CABDD', s: '#1C2C5B' },
    { p: '#8E1F2F', s: '#F1A624' },
    { p: '#1E71B8', s: '#000000' },
  ];
  const colorPair = customColor 
    ? { p: customColor, s: '#ffffff' }
    : colors[Math.abs(name.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0)) % colors.length];

  return {
    id: id || `custom-${Date.now()}`,
    name: name.trim(),
    shortName: name.split(' ')[0] || name,
    code: code || 'NEW',
    logo: 'https://images.unsplash.com/photo-1508098682722-e99c43a406b2?auto=format&fit=crop&w=120&h=120&q=80',
    primaryColor: colorPair.p,
    secondaryColor: colorPair.s,
    formation: '4-3-3',
  };
}

/**
 * Search the world teams directory by query
 */
export function searchWorldTeams(query: string, leagueFilter: string = 'ALL'): WorldTeamInfo[] {
  let list = WORLD_TEAMS;
  if (leagueFilter !== 'ALL') {
    list = list.filter((t) => t.league === leagueFilter);
  }
  if (!query || !query.trim()) return list;

  const q = query.toLowerCase().trim();
  return list.filter(
    (t) =>
      t.name.toLowerCase().includes(q) ||
      t.shortName.toLowerCase().includes(q) ||
      t.code.toLowerCase().includes(q) ||
      t.country.toLowerCase().includes(q) ||
      t.league.toLowerCase().includes(q) ||
      t.stadium.toLowerCase().includes(q) ||
      t.keyStars.some((s) => s.toLowerCase().includes(q))
  );
}

/**
 * Generate full 11-player squad + bench for any team, including marquee stars if known
 */
export function generateWorldSquad(team: Team, isHome: boolean): Player[] {
  const coords = getFormationCoordinates(team.formation || '4-3-3', isHome);
  const worldInfo = WORLD_TEAMS.find((t) => t.id === team.id || t.code === team.code);
  const knownStars = worldInfo?.keyStars || [];

  const genericNames = [
    'Goalkeeper',
    'Left Back',
    'Centre Back',
    'Centre Back',
    'Right Back',
    'Midfielder',
    'Playmaker',
    'Midfielder',
    'Winger',
    'Striker',
    'Winger',
    'Sub GK',
    'Sub Defender',
    'Sub Midfielder',
    'Sub Attacker',
  ];

  const genericNumbers = [1, 3, 4, 5, 2, 6, 8, 10, 7, 9, 11, 12, 14, 17, 19];

  // Starting XI
  const startingXI: Player[] = coords.map((posCoord, idx) => {
    // If we have a known star name for this position index
    const assignedName = knownStars[idx] || `${team.shortName} ${genericNames[idx]}`;
    const number = genericNumbers[idx] || (idx + 1);

    return {
      id: `${team.code.toLowerCase()}-${number}-${idx}`,
      teamId: team.id,
      name: assignedName,
      shortName: assignedName.split(' ').pop() || assignedName,
      number,
      position: posCoord.position,
      nationality: worldInfo?.country || 'International',
      age: 23 + (idx % 7),
      photo: `https://images.unsplash.com/photo-${1500000000000 + (idx * 314159) % 50000000}?auto=format&fit=crop&w=160&h=160&q=80`,
      rating: Number((7.4 + ((idx * 7) % 20) * 0.1).toFixed(1)),
      goals: idx >= 8 ? (idx % 3) : 0,
      assists: idx >= 5 ? 1 : 0,
      yellowCards: 0,
      redCards: 0,
      minutesPlayed: 75,
      isStarter: true,
      pitchX: posCoord.x,
      pitchY: posCoord.y,
    };
  });

  // Bench
  const subs: Player[] = [11, 12, 13, 14].map((subIdx, i) => {
    const assignedName = knownStars[subIdx] || `${team.shortName} Sub ${i + 1}`;
    const posList: PlayerPosition[] = ['GK', 'CB', 'CM', 'ST'];
    return {
      id: `${team.code.toLowerCase()}-${genericNumbers[subIdx] || (20 + i)}-sub-${i}`,
      teamId: team.id,
      name: assignedName,
      shortName: assignedName.split(' ').pop() || assignedName,
      number: genericNumbers[subIdx] || (20 + i),
      position: posList[i] || 'CM',
      nationality: worldInfo?.country || 'International',
      age: 21 + i,
      photo: 'https://images.unsplash.com/photo-1507003211169-0a1dd7228f2d?auto=format&fit=crop&w=160&h=160&q=80',
      rating: 7.2,
      goals: 0,
      assists: 0,
      yellowCards: 0,
      redCards: 0,
      minutesPlayed: 0,
      isStarter: false,
      pitchX: isHome ? 5 : 95,
      pitchY: 5,
    };
  });

  return [...startingXI, ...subs];
}
